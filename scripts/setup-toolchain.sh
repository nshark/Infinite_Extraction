#!/usr/bin/env bash
# Provision the pinned toolchain for Infinite Extraction.
#
# Installs, per-user and WITHOUT sudo, into <repo>/.toolchain (gitignored):
#   * Godot <GODOT_VERSION> .NET build  -> .toolchain/godot/
#   * .NET SDK (only if none is on PATH) -> $HOME/.dotnet
# Then generates the two solution files and restores packages.
#
# Idempotent: re-running is safe and skips anything already present.
# Supports macOS (universal) and Linux (x86_64 / arm64).
#
#   bash scripts/setup-toolchain.sh
#   source .toolchain/env.sh      # puts godot + dotnet on PATH for this shell
set -euo pipefail

GODOT_VERSION="4.7.1"
GODOT_FLAVOR="stable"
DOTNET_CHANNEL="8.0"

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
TOOLCHAIN_DIR="${IE_TOOLCHAIN_DIR:-$REPO_ROOT/.toolchain}"
GODOT_DIR="$TOOLCHAIN_DIR/godot"

log()  { printf '\033[1;34m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[1;33m[warn]\033[0m %s\n' "$*"; }
die()  { printf '\033[1;31m[fail]\033[0m %s\n' "$*" >&2; exit 1; }

# ---------------------------------------------------------------- platform ---
OS="$(uname -s)"
ARCH="$(uname -m)"
case "$OS:$ARCH" in
  Darwin:*)          GODOT_SLUG="mono_macos.universal.zip" ;;
  Linux:x86_64)      GODOT_SLUG="mono_linux_x86_64.zip" ;;
  Linux:aarch64|Linux:arm64) GODOT_SLUG="mono_linux_arm64.zip" ;;
  *) die "unsupported platform $OS/$ARCH" ;;
esac
GODOT_ASSET="Godot_v${GODOT_VERSION}-${GODOT_FLAVOR}_${GODOT_SLUG}"

mkdir -p "$TOOLCHAIN_DIR"

# ---------------------------------------------------------------- dotnet -----
if command -v dotnet >/dev/null 2>&1; then
  log ".NET SDK already on PATH: $(dotnet --version)"
  DOTNET_BIN="$(command -v dotnet)"
elif [ -x "$HOME/.dotnet/dotnet" ]; then
  log ".NET SDK found at \$HOME/.dotnet"
  DOTNET_BIN="$HOME/.dotnet/dotnet"
else
  log "installing .NET SDK $DOTNET_CHANNEL into \$HOME/.dotnet"
  curl -fsSL https://dot.net/v1/dotnet-install.sh -o "$TOOLCHAIN_DIR/dotnet-install.sh" \
    || die "could not download dotnet-install.sh (network blocked?)"
  bash "$TOOLCHAIN_DIR/dotnet-install.sh" --channel "$DOTNET_CHANNEL" --install-dir "$HOME/.dotnet"
  DOTNET_BIN="$HOME/.dotnet/dotnet"
fi
# A Homebrew/symlinked dotnet lives in a bin dir that is not a DOTNET_ROOT, so only
# set it when the directory actually holds an sdk/.
DOTNET_DIR="$(cd "$(dirname "$DOTNET_BIN")" && pwd)"
if [ -d "$DOTNET_DIR/sdk" ]; then
  export DOTNET_ROOT="$DOTNET_DIR"
fi
export PATH="$DOTNET_DIR:$PATH"

# ---------------------------------------------------------------- godot ------
find_godot_bin() {
  # macOS ships an .app bundle; Linux ships a bare executable. Locate either.
  find "$GODOT_DIR" -maxdepth 4 \( -path '*Godot*.app/Contents/MacOS/Godot' -o -name 'Godot_v*_mono_linux.*' \) \
    -type f -print 2>/dev/null | head -n 1
}

GODOT_BIN="$(find_godot_bin || true)"
if [ -n "${GODOT_BIN:-}" ]; then
  log "Godot already installed: $GODOT_BIN"
else
  log "downloading $GODOT_ASSET"
  mkdir -p "$GODOT_DIR"
  ZIP="$TOOLCHAIN_DIR/$GODOT_ASSET"
  PRIMARY="https://github.com/godotengine/godot/releases/download/${GODOT_VERSION}-${GODOT_FLAVOR}/${GODOT_ASSET}"
  MIRROR="https://downloads.godotengine.org/?version=${GODOT_VERSION}&flavor=${GODOT_FLAVOR}&slug=${GODOT_SLUG}"
  curl -fL --retry 3 -o "$ZIP" "$PRIMARY" || curl -fL --retry 3 -o "$ZIP" "$MIRROR" \
    || die "could not download Godot from GitHub or downloads.godotengine.org"
  unzip -q -o "$ZIP" -d "$GODOT_DIR"
  rm -f "$ZIP"
  GODOT_BIN="$(find_godot_bin || true)"
  [ -n "${GODOT_BIN:-}" ] || die "unpacked $GODOT_ASSET but found no Godot executable under $GODOT_DIR"
  chmod +x "$GODOT_BIN"
fi

# macOS quarantines downloaded bundles; strip it so the binary will launch.
if [ "$OS" = "Darwin" ]; then
  xattr -dr com.apple.quarantine "$GODOT_DIR" 2>/dev/null || true
fi

# ---------------------------------------------------------------- env.sh -----
cat > "$TOOLCHAIN_DIR/env.sh" <<ENVEOF
# Generated by scripts/setup-toolchain.sh -- source this, do not edit.
export IE_REPO_ROOT="$REPO_ROOT"
export GODOT_BIN="$GODOT_BIN"
export DOTNET_ROOT="${DOTNET_ROOT:-$DOTNET_DIR}"
export PATH="$DOTNET_DIR:\$PATH"
alias godot="\$GODOT_BIN"
ENVEOF
log "wrote $TOOLCHAIN_DIR/env.sh"

# ---------------------------------------------------------------- solutions --
# Hand-written .sln files rot; let the CLI generate them.
#   * InfiniteExtraction.sln (repo root) -- what dotnet build/test use.
#   * app/IE.App.sln                     -- what the Godot editor expects to find
#                                           next to project.godot. If it is missing,
#                                           Godot regenerates one on open.
cd "$REPO_ROOT"
if [ ! -f "InfiniteExtraction.sln" ]; then
  log "creating InfiniteExtraction.sln"
  "$DOTNET_BIN" new sln -n InfiniteExtraction >/dev/null
  "$DOTNET_BIN" sln InfiniteExtraction.sln add \
    src/IE.Model/IE.Model.csproj \
    src/IE.Controller/IE.Controller.csproj \
    src/IE.ViewMath/IE.ViewMath.csproj \
    app/IE.App.csproj \
    tests/IE.Tests/IE.Tests.csproj >/dev/null
fi

if [ ! -f "app/IE.App.sln" ]; then
  log "creating app/IE.App.sln (Godot editor solution)"
  ( cd app && "$DOTNET_BIN" new sln -n IE.App >/dev/null \
    && "$DOTNET_BIN" sln IE.App.sln add \
        IE.App.csproj \
        ../src/IE.Model/IE.Model.csproj \
        ../src/IE.Controller/IE.Controller.csproj \
        ../src/IE.ViewMath/IE.ViewMath.csproj >/dev/null )
fi

# ---------------------------------------------------------------- verify -----
log "restoring packages"
"$DOTNET_BIN" restore InfiniteExtraction.sln

log "importing Godot resources (headless)"
"$GODOT_BIN" --headless --path "$REPO_ROOT/app" --import --quit-after 200 >/dev/null 2>&1 || \
  warn "headless import returned non-zero; check 'scripts/run.sh --headless' output"

printf '\n'
log "toolchain ready"
printf '    godot : %s (%s)\n' "$GODOT_BIN" "$("$GODOT_BIN" --version 2>/dev/null | head -n1)"
printf '    dotnet: %s (%s)\n' "$DOTNET_BIN" "$("$DOTNET_BIN" --version)"
printf '\nNext: source .toolchain/env.sh && scripts/test.sh\n'
